import { Pinecone, RecordMetadata } from "@pinecone-database/pinecone";
import { GoogleGenAI } from "@google/genai";

// Ensure RecordMetadata compliance for Pinecone Custom Field Maps
interface FinancialMetadata extends RecordMetadata {
  text: string;
  ticker: string;
}

// Initialize clients safely with environment fallback protections
const getPineconeIndex = () => {
  if (!process.env.PINECONE_API_KEY || !process.env.PINECONE_INDEX) return null;
  const pc = new Pinecone({ apiKey: process.env.PINECONE_API_KEY });
  return pc.index<FinancialMetadata>({ name: process.env.PINECONE_INDEX! });
};

const ai = new GoogleGenAI({ apiKey: process.env.GEMINI_API_KEY! });

/**
 * PHASE 1: Fetches live financial news and updates the Pinecone knowledge graph.
 */
export async function ingestCloudFinancialNews(tickerSymbol: string) {
  const index = getPineconeIndex();
  if (!index) throw new Error("Cloud Vector Database Configuration Missing");

  const today = new Date();
  const pastDate = new Date();
  pastDate.setDate(today.getDate() - 7); // Pull news from the past 7 days

  const formatDate = (date: Date) => date.toISOString().split("T")[0];

  const fromStr = formatDate(pastDate);
  const toStr = formatDate(today);

  // Fetch data from Finnhub Company News Endpoint
  const apiKey = process.env.FINNHUB_API_KEY;
  if (!apiKey)
    throw new Error("FINNHUB_API_KEY environment variable is missing");

  const url = `https://finnhub.io{tickerSymbol}&from=${fromStr}&to=${toStr}&token=${apiKey}`;

  const newsResponse = await fetch(url, { method: "GET" });
  const newsData = await newsResponse.json();

  if (!newsResponse.ok || !Array.isArray(newsData)) {
    throw new Error(newsData.error || "Failed to pull Finnhub data feeds.");
  }

  // Format articles to fit Llama Integrated Embedding target field maps
  const articlesToIngest = newsData.slice(0, 5).map((art: any) => ({
    content: `${art.headline}. ${art.summary || ""}`,
  }));

  if (articlesToIngest.length === 0) {
    return {
      status: "completed",
      detail: `No new Finnhub stories found for ${tickerSymbol} this week.`,
    };
  }

  const vectors = articlesToIngest.map((art: any, i: number) => ({
    id: `cloud-${tickerSymbol}-${Date.now()}-${i}`,
    data: art.content, // Feeds plain text to the Llama integrated embedder
    metadata: {
      text: art.content,
      ticker: tickerSymbol,
    },
  }));

  await index.upsert({ records: vectors });

  return {
    status: "completed",
    detail: `Successfully updated cloud knowledge for ${tickerSymbol}`,
  };
}

/**
 * PHASE 2: Queries the Integrated Vector Index and synthesizes insights using Gemini.
 */
export async function queryCloudFinancialRag(
  tickerSymbol: string,
  question: string,
) {
  const index = getPineconeIndex();
  if (!index) throw new Error("Cloud Vector Database Configuration Missing");

  // Perform a semantic lookup across your text fields natively
  const queryResponse = await index.searchRecords({
    query: {
      topK: 4,
      inputs: { text: question },
      filter: { ticker: { $eq: tickerSymbol } },
    },
    fields: ["text"],
  });

  // Extract contextual insights safely without throwing schema object index warnings
  const retrievedContext =
    queryResponse.result?.hits
      ?.map((hit) => {
        const fields = hit.fields as Record<string, any>;
        return fields?.text as string;
      })
      .filter(Boolean)
      .join("\n\n") || "No historical document chunks found for this asset.";

  // Generate a flat, structured financial report
  const aiResponse = await ai.models.generateContent({
    model: "gemini-3.8-flash",
    config: {
      systemInstruction: `You are an expert financial AI core analyst for the stock symbol: ${tickerSymbol}. 
      Answer using the parsed historical document contexts below. 
      If the context does not contain relevant insights, explicitly flag it.
      
      CONTEXT:
      ${retrievedContext}`,
    },
    contents: question,
  });

  return {
    answer: aiResponse.text || "No summary text generated by Gemini.",
  };
}
